"""# Aplicar normalização e encoding:

## Normalizar colunas numéricas (por exemplo, preço, idade ou renda).
"""

def normalizar_coluna(df, coluna):
    df = df.copy()  # não altera o DataFrame original
    minimo = df[coluna].min()
    maximo = df[coluna].max()
    df[f'{coluna}_norm'] = (df[coluna] - minimo) / (maximo - minimo)
    return df

