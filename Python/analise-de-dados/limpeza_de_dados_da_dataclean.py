def outliers_iqr(df, coluna):
    Q1 = df[coluna].quantile(0.25)
    Q3 = df[coluna].quantile(0.75)
    IQR = Q3 - Q1
    lim_inf = Q1 - 1.5 * IQR
    lim_sup = Q3 + 1.5 * IQR

    outliers = df[(df[coluna] < lim_inf) | (df[coluna] > lim_sup)]

    print(f'--- {coluna} ---')
    print(f'Q1={Q1:.2f} | Q3={Q3:.2f} | IQR={IQR:.2f}')
    print(f'Limite inferior: {lim_inf:.2f} | Limite superior: {lim_sup:.2f}')
    print(f'Outliers encontrados: {len(outliers)}\n')
    return outliers

outliers_idade  = outliers_iqr(df, 'idade')
outliers_renda  = outliers_iqr(df, 'renda_anual')
outliers_compra = outliers_iqr(df, 'valor_compra')

